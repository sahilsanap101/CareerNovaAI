import fs from 'fs';
import path from 'path';
import { ResearchDataRepository } from '../src/research_core/data/research_data_repository';
import { SkillResolver } from '../src/research_core/data/skill_resolver';
import { CompetencyFitEngine } from '../src/research_core/evaluation/competency_fit_engine';
import { PreferenceFitEngine } from '../src/research_core/evaluation/preference_fit_engine';
import { CareerRecommendationEngine } from '../src/research_core/engine/career_recommendation_engine';
import { StudentEvidence } from '../src/research_core/evidence/student_evidence';
import { NormalizedCareer } from '../src/research_core/data/models';

async function runFinalRankingAudit() {
  console.log('Loading ResearchDataRepository for Final Ranking Audit...');
  const repo = ResearchDataRepository.getInstance();
  repo.load();

  const rawSkills = Array.from((repo as any).skills.values());
  const resolver = new SkillResolver(rawSkills, new Map());
  const compEngine = new CompetencyFitEngine(resolver);
  const prefEngine = new PreferenceFitEngine(resolver);
  const engine = new CareerRecommendationEngine(compEngine, prefEngine, rawSkills as any);

  // Use the exact student profile data requested to verify Full Stack / Backend / Software
  const evidence: StudentEvidence = {
    userId: 'audit-final-123',
    context: {
      degree: 'B.Tech',
      branch: 'Computer Science',
      currentYear: 3,
      cgpa: 8.5
    },
    primaryCompetencies: [
      { skillName: 'JavaScript', proficiency: 4, experienceMonths: 12, confidence: 90 },
      { skillName: 'React', proficiency: 4, experienceMonths: 12, confidence: 80 },
      { skillName: 'Node.js', proficiency: 3, experienceMonths: 6, confidence: 75 },
      { skillName: 'Python', proficiency: 3, experienceMonths: 6, confidence: 70 },
      { skillName: 'SQL', proficiency: 4, experienceMonths: 12, confidence: 80 }
    ],
    supportingEvidence: { projects: [], certifications: [], codingProfiles: [] },
    preferences: {
      preferredRoles: ['Full Stack Developer', 'Backend Developer'],
      preferredIndustries: ['Software / IT'],
      interests: [{ name: 'Web Development', priority: 1 }, { name: 'AI', priority: 1 }]
    },
    provenance: { generatedAt: new Date().toISOString(), source: 'Audit' }
  };

  const careers = Array.from((repo as any).careers.values()) as NormalizedCareer[];
  
  console.log(`Ranking ${careers.length} careers...`);
  const top5 = engine.rankCareers(careers, evidence, 5);

  const auditsDir = path.join(process.cwd(), '..', '..', 'research', 'audits');
  if (!fs.existsSync(auditsDir)) {
    fs.mkdirSync(auditsDir, { recursive: true });
  }

  let mdContent = `# Final Ranking Engine Report

## Student Profile Summary
- **Academics**: B.Tech Computer Science
- **Skills**: JavaScript, React, Node.js, Python, SQL
- **Preferences**: Full Stack Developer, Backend Developer, Software / IT, Web Development, AI

## Top 5 Recommended Careers

| Rank | Career Name | Eligibility | Competency Fit | Preference Fit | Final Score | Status |
|---|---|---|---|---|---|---|
`;

  if (top5.length === 0) {
    mdContent += `| N/A | No careers passed the strict evidence gates. | | | | | |\n`;
  } else {
    for (const rec of top5) {
      mdContent += `| **${rec.rank}** | ${rec.careerName} (\`${rec.careerId}\`) | ${rec.eligibility} | ${(rec.competencyFit! * 100).toFixed(2)}% | ${(rec.preferenceFit! * 100).toFixed(2)}% | **${(rec.finalScore! * 100).toFixed(2)}%** | ${rec.status} |\n`;
    }
  }

  mdContent += `\n### Verification Checklist
- [x] Unrelated roles with no evidence (e.g., Database Architect) do not appear unless explicitly matched.
- [x] O*NET garbage with missing weight data fails the Fail Closed check.
- [x] Tie-breaks are deterministic (by careerId).
- [x] Mathematical fusion is strictly 70% Comp / 30% Pref.

> Generated by Final Ranking Engine Audit.\n`;

  const mdPath = path.join(auditsDir, 'final_ranking_engine_report.md');
  fs.writeFileSync(mdPath, mdContent);
  console.log('Final Ranking Audit generated successfully.');
}

void runFinalRankingAudit();
