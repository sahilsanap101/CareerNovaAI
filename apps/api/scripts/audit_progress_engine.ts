import fs from 'fs';
import path from 'path';
import { RoadmapProgressEngine, NodeProgress } from '../src/research_core/engine/roadmap_progress_engine';
import { RoadmapEngine } from '../src/research_core/engine/roadmap_engine';
import { NormalizedCareer } from '../src/research_core/data/models';
import { StudentEvidence } from '../src/research_core/evidence/student_evidence';
import { SkillGapTrace } from '../src/research_core/evaluation/skill_gap_engine';
import { DependencyGraph } from '../src/research_core/data/dependency_engine';

async function runProgressAudit() {
  console.log('Evaluating Roadmap Progress and Adaptation System...');

  const progressEngine = new RoadmapProgressEngine(new RoadmapEngine());

  const career: NormalizedCareer = {
    careerId: 'c1',
    careerName: 'Software Developer',
    category: 'Engineering',
    industry: 'Tech',
    requiredSkills: ['JavaScript', 'TypeScript', 'React', 'Node.js'],
    importanceWeights: { 'JavaScript': 1.0, 'TypeScript': 0.8, 'React': 0.9, 'Node.js': 0.7 },
    academicConstraints: [],
    dependencyRelations: {},
    provenance: 'test'
  };

  const evidence: StudentEvidence = {
    userId: 'audit-student',
    context: { year: '4' },
    primaryCompetencies: [],
    supportingEvidence: { projects: [], certifications: [], codingProfiles: [] },
    preferences: { preferredRoles: [], preferredIndustries: [], interests: [] },
    provenance: { generatedAt: new Date().toISOString(), source: 'Test' }
  };

  const skillGaps: SkillGapTrace[] = career.requiredSkills.map(skill => ({
    skill,
    status: 'MISSING',
    studentCompetency: 0,
    targetCompetency: 'TARGET_NOT_AVAILABLE',
    gapSeverity: null,
    importance: career.importanceWeights[skill] || 1,
    mappingMethod: 'EXACT',
    provenance: 'Audit'
  }));

  const graph: DependencyGraph = {
    nodes: career.requiredSkills.map(skill => ({ id: skill, label: skill })),
    edges: [],
    validation: { hasCycles: false, invalidReferences: [], selfLoops: [], duplicateEdges: [], disconnectedNodes: [] }
  };

  // State 1: No progress
  const rmp1 = progressEngine.adaptRoadmap(career, evidence, skillGaps, graph, []);

  // State 2: Student completes 'JavaScript' and 'React'
  const progress: NodeProgress[] = [
    { skillId: 'JavaScript', status: 'COMPLETED', completedAt: new Date().toISOString() },
    { skillId: 'React', status: 'COMPLETED', completedAt: new Date().toISOString() }
  ];

  const rmp2 = progressEngine.adaptRoadmap(career, evidence, skillGaps, graph, progress);

  const auditsDir = path.join(process.cwd(), '..', '..', 'research', 'audits');
  if (!fs.existsSync(auditsDir)) {
    fs.mkdirSync(auditsDir, { recursive: true });
  }

  let mdContent = `# Roadmap Progress and Adaptation System Report

## Engine Strategy
> As strictly mandated, **COMPLETED learning task != COMPETENCY VERIFIED**. The engine did not modify the raw Skill Gaps or Student Evidence. Instead, it temporarily intercepted the array, marked the completed skills as \`MATCHED\`, and piped them into the topology generator.
> The historical completed nodes are safely preserved in \`completedNodes\`, completely separate from the remaining \`activeNodes\`.

## State 1: Zero Progress
- **Completed Nodes**: ${rmp1.completedNodes.length}
- **Active Nodes**: ${rmp1.activeNodes.length}
- **Active Order**: ${rmp1.activeNodes.map(n => n.skill).join(', ')}

## State 2: Student completes 'JavaScript' and 'React'
- **Completed Nodes**: ${rmp2.completedNodes.length}
- **Active Nodes**: ${rmp2.activeNodes.length}
- **Active Order**: ${rmp2.activeNodes.map(n => n.skill).join(', ')}

### Proof of Adaptation (State 2 Export)
\`\`\`json
${JSON.stringify({
  versionId: rmp2.metadata.versionId,
  completedNodes: rmp2.completedNodes.map(n => n.skillId),
  activeNodes: rmp2.activeNodes.map(n => n.skill)
}, null, 2)}
\`\`\`

> Generated by Roadmap Progress Engine Audit.\n`;

  const mdPath = path.join(auditsDir, 'progress_adaptation_report.md');
  fs.writeFileSync(mdPath, mdContent);
  console.log('Progress Engine Audit generated successfully.');
}

void runProgressAudit();
