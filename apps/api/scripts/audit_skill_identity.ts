import fs from 'fs';
import path from 'path';
import { ResearchDataRepository } from '../src/research_core/data/research_data_repository';
import { SkillResolver } from '../src/research_core/data/skill_resolver';

async function runSkillIdentityAudit() {
  console.log('Loading ResearchDataRepository for Skill Identity Audit...');
  const repo = ResearchDataRepository.getInstance();
  repo.load();

  // Construct resolver from repository
  const rawSkills = Array.from((repo as any).skills.values());
  const crosswalkMap = new Map<string, string>();
  // We can add some manual crosswalks to test
  crosswalkMap.set('React', 'esco:3e17dfa7-ecbb-4034-bc69-23ce5a2d6778'); // Just an example, let's let exact match handle 'React.js' if it exists.
  
  const resolver = new SkillResolver(rawSkills, crosswalkMap);

  const testSkills = [
    'Python',
    'JavaScript',
    'React',
    'React.js',
    'Node.js',
    'SQL',
    'Machine Learning',
    'unknown framework 123',
    'java programming',
    'c++'
  ];

  const auditsDir = path.join(process.cwd(), '..', '..', 'research', 'audits');
  if (!fs.existsSync(auditsDir)) {
    fs.mkdirSync(auditsDir, { recursive: true });
  }

  let mdContent = `# Skill Identity Engine Report

## Configuration
- **Total Skills Loaded**: ${rawSkills.length}
- **LLM Usage**: None (Strict deterministic resolution)

## Trace Examples

| Input Skill | Status | Resolved Identity (Canonical ID) | Match Method | Source |
|---|---|---|---|---|
`;

  for (const skill of testSkills) {
    const trace = resolver.resolve(skill);
    mdContent += `| \`${skill}\` | **${trace.mappingStatus}** | \`${trace.resolvedIdentity || 'N/A'}\` | ${trace.matchingMethod} | ${trace.sourceNamespace || 'N/A'} |\n`;
  }

  mdContent += `\n> Generated by Skill Identity Engine Audit.\n`;

  const mdPath = path.join(auditsDir, 'skill_identity_engine_report.md');
  fs.writeFileSync(mdPath, mdContent);
  console.log('Skill Identity Audit generated successfully.');
}

void runSkillIdentityAudit();
