import fs from 'fs';
import path from 'path';
import { ResourceRegistry, LearningResource } from '../src/research_core/data/resource_registry';

async function runResourceRegistryAudit() {
  console.log('Evaluating Verified Learning Resource System...');
  
  const registry = new ResourceRegistry();
  
  // Inject synthetic test data to prove the filters
  registry.loadResources([
    {
      resourceId: 'test-valid-1',
      title: 'React Official Documentation',
      type: 'OFFICIAL_DOCUMENTATION',
      provider: 'Meta',
      url: 'https://react.dev',
      skill: 'react-skill-id',
      difficulty: 'BEGINNER',
      freeOrPaid: 'FREE',
      source: 'Curated',
      status: 'VERIFIED',
      geminiExplanation: 'This is the official documentation, ensuring you learn React according to the core team\'s standard practices.'
    },
    {
      resourceId: 'test-invalid-1',
      title: 'Fake AI Generated Book',
      type: 'BOOK',
      provider: 'Hallucination',
      url: 'https://amazon.com/fake-book',
      skill: 'react-skill-id',
      difficulty: 'ADVANCED',
      source: 'LLM',
      status: 'UNVERIFIED'
    }
  ]);

  // Request for skill with mix
  const mixedResult = registry.getResourcesForSkill('react-skill-id');

  // Request for skill with NO resources
  const emptyResult = registry.getResourcesForSkill('unknown-skill');

  const auditsDir = path.join(process.cwd(), '..', '..', 'research', 'audits');
  if (!fs.existsSync(auditsDir)) {
    fs.mkdirSync(auditsDir, { recursive: true });
  }

  let mdContent = `# Verified Learning Resource System Report

## Engine Strategy
> As strictly mandated, the engine aggressively protects the production UI from hallucinated links. It natively filters out any resource where \`status !== 'VERIFIED'\`.
> If no verified resources exist for a skill, the engine explicitly yields \`NOT_AVAILABLE\`.

## Scenario 1: Mixed Resource Validation (React)
- **Status Returned**: \`${mixedResult.resourcesStatus}\`
- **Total Injected**: 2 (1 VERIFIED, 1 UNVERIFIED)
- **Total Exposed to UI**: ${mixedResult.resources.length}
- **Did the fake book leak?**: \`${mixedResult.resources.some(r => r.status !== 'VERIFIED')}\`

### Safe JSON Export (UI Bound)
\`\`\`json
${JSON.stringify(mixedResult, null, 2)}
\`\`\`

## Scenario 2: Zero Verified Resources (Unknown Skill)
- **Status Returned**: \`${emptyResult.resourcesStatus}\`
- **Total Exposed to UI**: ${emptyResult.resources.length}

### Safe JSON Export (UI Bound)
\`\`\`json
${JSON.stringify(emptyResult, null, 2)}
\`\`\`

> Generated by Resource Registry Audit.\n`;

  const mdPath = path.join(auditsDir, 'resource_registry_report.md');
  fs.writeFileSync(mdPath, mdContent);
  console.log('Resource Registry Audit generated successfully.');
}

void runResourceRegistryAudit();
