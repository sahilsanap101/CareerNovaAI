import fs from 'fs';
import path from 'path';
import { ResearchDataRepository } from '../src/research_core/data/research_data_repository';

async function runUniverseAudit() {
  console.log('Loading ResearchDataRepository for Universe Audit...');
  const repo = ResearchDataRepository.getInstance();
  repo.load();

  const careers = repo.getCareers();
  const auditsDir = path.join(process.cwd(), '..', '..', 'research', 'audits');
  
  if (!fs.existsSync(auditsDir)) {
    fs.mkdirSync(auditsDir, { recursive: true });
  }

  const eligibleCareers = careers.filter(c => c.careerRecommendationEligible);
  const excludedCareers = careers.filter(c => !c.careerRecommendationEligible);

  const mdPath = path.join(auditsDir, 'career_universe_report.md');
  const mdContent = `# CareerNova Placement Universe Report

## Overview
- **Total Careers in Dataset**: ${careers.length}
- **Placement Eligible Universe**: ${eligibleCareers.length}
- **Excluded**: ${excludedCareers.length}

## Included Careers (Placement Universe)
${eligibleCareers.map(c => `- **${c.careerName}** (${c.careerId}) | Family: ${c.careerFamily} | Skills: ${c.requiredSkills.length} | Health: ${c.healthStatus?.mappingHealth}`).join('\n')}

## Excluded Careers
${excludedCareers.map(c => {
    const reason = c.placementRelevant === false ? 'Irrelevant to target population' : (c.healthStatus?.requirementsValid ? 'Unknown' : 'Insufficient skill evidence');
    return `- **${c.careerName}** (${c.careerId}) | Reason: ${reason}`;
}).join('\n')}

> Generated by ResearchDataRepository Universe Audit.
`;

  fs.writeFileSync(mdPath, mdContent);
  console.log('Universe Audit generated successfully.');
}

void runUniverseAudit();
