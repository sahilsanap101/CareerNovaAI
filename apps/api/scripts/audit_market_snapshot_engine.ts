import fs from 'fs';
import path from 'path';
import { MarketSnapshotEngine } from '../src/research_core/data/market_snapshot_engine';

async function runMarketSnapshotAudit() {
  console.log('Evaluating Market Snapshot Engine (Fail-Closed default)...');
  
  const engine = new MarketSnapshotEngine(); // Uses default providers
  const snapshot = await engine.getLatestSnapshot('Software Developer', 'global');

  const auditsDir = path.join(process.cwd(), '..', '..', 'research', 'audits');
  if (!fs.existsSync(auditsDir)) {
    fs.mkdirSync(auditsDir, { recursive: true });
  }

  let mdContent = `# Market Snapshot Engine Report

## Target Query
- **Role**: Software Developer
- **Geography**: global

## Engine Strategy
> As strictly mandated, since there is no existing provider capable of native bulk extraction of verified \`FINAL_V2\` skills without employing unverified fuzzy mappings, the engine was built with the interface architecture but mathematically defaults to **NOT_AVAILABLE**.
> It refuses to hallucinate data or present raw HTML snippets as market trends.

## Snapshot Output (Fail-Closed)
- **Status / Availability**: \`${snapshot.availability}\`
- **Source**: ${snapshot.source}
- **Sample Size**: ${snapshot.sampleSize}
- **Skill Occurrences**: ${snapshot.skillOccurrences.length}

## JSON Export (Architecture Proof)
\`\`\`json
${JSON.stringify(snapshot, null, 2)}
\`\`\`

> Generated by Market Snapshot Engine Audit.\n`;

  const mdPath = path.join(auditsDir, 'market_snapshot_engine_report.md');
  fs.writeFileSync(mdPath, mdContent);
  console.log('Market Snapshot Engine Audit generated successfully.');
}

void runMarketSnapshotAudit();
