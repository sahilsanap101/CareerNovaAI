import fs from 'fs';
import path from 'path';
import { ResearchDataRepository } from '../src/research_core/data/research_data_repository';

async function runAudit() {
  console.log('Loading ResearchDataRepository...');
  const repo = ResearchDataRepository.getInstance();
  repo.load();

  const metadata = repo.getResearchMetadata();
  const auditsDir = path.join(process.cwd(), '..', '..', 'research', 'audits');
  
  if (!fs.existsSync(auditsDir)) {
    fs.mkdirSync(auditsDir, { recursive: true });
  }

  const manifestPath = path.join(auditsDir, 'final_v2_runtime_manifest.json');
  fs.writeFileSync(manifestPath, JSON.stringify(metadata, null, 2));

  const mdPath = path.join(auditsDir, 'final_v2_data_audit.md');
  const mdContent = `# FINAL_V2 Dataset Audit

## Metadata
- **Version Hash (MD5)**: \`${metadata.versionHash}\`
- **Loaded At**: ${metadata.loadedAt}

## Statistics
- **Total Careers**: ${metadata.careerCount}
- **Total Skills**: ${metadata.skillCount}
- **Total Requirements**: ${metadata.requirementCount}
- **Total Dependencies**: ${metadata.dependencyCount}

## Provenance
${metadata.provenance.map(p => `- ${p}`).join('\n')}

> Generated by ResearchDataRepository initialization check.
`;

  fs.writeFileSync(mdPath, mdContent);
  console.log('Audit generated successfully.');
}

void runAudit();
