import fs from 'fs';
import path from 'path';
import { ResearchDataRepository } from '../src/research_core/data/research_data_repository';
import { SkillResolver } from '../src/research_core/data/skill_resolver';
import { CompetencyFitEngine } from '../src/research_core/evaluation/competency_fit_engine';
import { StudentEvidence } from '../src/research_core/evidence/student_evidence';

async function runCompetencyFitAudit() {
  console.log('Loading ResearchDataRepository for Competency Fit Audit...');
  const repo = ResearchDataRepository.getInstance();
  repo.load();

  const rawSkills = Array.from((repo as any).skills.values());
  const resolver = new SkillResolver(rawSkills, new Map());
  const engine = new CompetencyFitEngine(resolver);

  // Use a career that has valid skills and importance weights
  const careers = Array.from((repo as any).careers.values()) as any[];
  // Find a career that has placementRelevant and required skills
  const targetCareer = careers.find(c => c.placementRelevant && c.requiredSkills.length > 5);

  if (!targetCareer) {
    console.warn('Could not find a valid career for testing.');
    return;
  }

  // Pick some required skills to simulate a partial match
  const requiredSkillIds = targetCareer.requiredSkills.slice(0, 3);
  const resolvedSkillsToMatch = requiredSkillIds.map((id: string) => rawSkills.find((s: any) => s.canonicalId === id));

  const evidence: StudentEvidence = {
    userId: 'audit-123',
    context: {},
    primaryCompetencies: [
      { skillName: resolvedSkillsToMatch[0]?.normalizedName || 'Unknown1', proficiency: 5, experienceMonths: 12, confidence: 90 },
      { skillName: resolvedSkillsToMatch[1]?.normalizedName || 'Unknown2', proficiency: 3, experienceMonths: 6, confidence: 50 },
      { skillName: 'Random Unmapped Skill', proficiency: 4, experienceMonths: 0, confidence: 0 }
    ],
    supportingEvidence: { projects: [], certifications: [], codingProfiles: [] },
    preferences: { preferredRoles: [], preferredIndustries: [], interests: [] },
    provenance: { generatedAt: new Date().toISOString(), source: 'Audit' }
  };

  const result = engine.evaluateFit(evidence, targetCareer);

  const auditsDir = path.join(process.cwd(), '..', '..', 'research', 'audits');
  if (!fs.existsSync(auditsDir)) {
    fs.mkdirSync(auditsDir, { recursive: true });
  }

  let mdContent = `# Competency Fit Engine Report

## Target Career
- **Career ID**: \`${targetCareer.careerId}\`
- **Career Name**: ${targetCareer.careerName}
- **Required Skills Count**: ${targetCareer.requiredSkills.length}

## Student Evidence
- Matches attempted against 2 required skills and 1 unmapped skill.

## Evaluation Result
- **Status**: \`${result.competencyFitStatus}\`
- **Calculated Fit**: \`${result.competencyFit !== null ? (result.competencyFit * 100).toFixed(2) + '%' : 'N/A'}\`

## Detailed Traces

| Required Skill ID | Student Competency (0-1) | Importance Weight | Contribution | Trace Status |
|---|---|---|---|---|
`;

  // For brevity in the report, show first 10 traces
  const displayTraces = result.traces.slice(0, 10);
  for (const trace of displayTraces) {
    const traceStatus = trace.mapping ? trace.mapping.mappingStatus : 'UNMAPPED';
    mdContent += `| \`${trace.skill}\` | ${trace.studentCompetency} | ${trace.importance} | ${trace.contribution.toFixed(2)} | ${traceStatus} |\n`;
  }
  
  if (result.traces.length > 10) {
    mdContent += `| ... | ... | ... | ... | ... |\n`;
    mdContent += `\n*Showing 10 of ${result.traces.length} total required skills.*\n`;
  }

  mdContent += `\n> Generated by Competency Fit Engine Audit.\n`;

  const mdPath = path.join(auditsDir, 'competency_fit_engine_report.md');
  fs.writeFileSync(mdPath, mdContent);
  console.log('Competency Fit Audit generated successfully.');
}

void runCompetencyFitAudit();
